USE sales_management_db;

-- =======================================================================
-- SECTION 1: BASIC QUERIES
-- =======================================================================

-- Query 1: Retrieve all records from the customer_sales table.
-- Description: Fetches every recorded sales transaction across the organization.
SELECT 
    sale_id,
    branch_id,
    date,
    name,
    mobile_number,
    product_name,
    gross_sales,
    received_amount,
    pending_amount,
    status
FROM customer_sales;

-- Query 2: Retrieve all records from the branches table.
-- Description: Fetches all registered branches and their designated administrators.
SELECT 
    branch_id,
    branch_name,
    branch_admin_name
FROM branches;

-- Query 3: Retrieve all records from the payment_splits table.
-- Description: Lists every individual payment split transaction recorded in the system.
SELECT 
    payment_id,
    sale_id,
    payment_date,
    amount_paid,
    payment_method
FROM payment_splits;

-- Query 4: Display all sales with status = 'Open'.
-- Description: Retrieves pending transactions requiring customer payment collection.
SELECT 
    sale_id,
    branch_id,
    date,
    name,
    mobile_number,
    product_name,
    gross_sales,
    received_amount,
    pending_amount,
    status
FROM customer_sales
WHERE status = 'Open';

-- Query 5: Retrieve all sales belonging to the Chennai branch.
-- Description: Filters sales records strictly for Chennai branch operations.
SELECT 
    cs.sale_id,
    b.branch_name,
    cs.date,
    cs.name AS customer_name,
    cs.mobile_number,
    cs.product_name,
    cs.gross_sales,
    cs.received_amount,
    cs.pending_amount,
    cs.status
FROM customer_sales cs
JOIN branches b ON cs.branch_id = b.branch_id
WHERE b.branch_name = 'Chennai';


-- =======================================================================
-- SECTION 2: AGGREGATION QUERIES
-- =======================================================================

-- Query 6: Calculate the total gross sales across all branches.
-- Description: Aggregates total gross revenue generated by the business.
SELECT 
    COALESCE(SUM(gross_sales), 0.00) AS total_gross_sales
FROM customer_sales;

-- Query 7: Calculate the total received amount across all sales.
-- Description: Aggregates total payments collected to date across all sales.
SELECT 
    COALESCE(SUM(received_amount), 0.00) AS total_received_amount
FROM customer_sales;

-- Query 8: Calculate the total pending amount across all sales.
-- Description: Aggregates outstanding balances waiting to be collected.
SELECT 
    COALESCE(SUM(pending_amount), 0.00) AS total_pending_amount
FROM customer_sales;

-- Query 9: Count the total number of sales per branch.
-- Description: Measures transaction volume for each branch.
SELECT 
    b.branch_id,
    b.branch_name,
    COUNT(cs.sale_id) AS total_sales_count
FROM branches b
LEFT JOIN customer_sales cs ON b.branch_id = cs.branch_id
GROUP BY b.branch_id, b.branch_name
ORDER BY total_sales_count DESC;

-- Query 10: Find the average gross sales amount.
-- Description: Calculates average order value (AOV) per transaction.
SELECT 
    ROUND(AVG(gross_sales), 2) AS average_gross_sales
FROM customer_sales;


-- =======================================================================
-- SECTION 3: JOIN-BASED QUERIES
-- =======================================================================

-- Query 11: Retrieve sales details along with the branch name.
-- Description: Combines customer sales records with branch names using INNER JOIN.
SELECT 
    cs.sale_id,
    b.branch_name,
    cs.date,
    cs.name AS customer_name,
    cs.product_name,
    cs.gross_sales,
    cs.pending_amount,
    cs.status
FROM customer_sales cs
INNER JOIN branches b ON cs.branch_id = b.branch_id
ORDER BY cs.sale_id ASC;

-- Query 12: Retrieve sales details along with total payment received (using payment_splits).
-- Description: Verifies payments received by summing payment_splits per sale.
SELECT 
    cs.sale_id,
    cs.name AS customer_name,
    cs.product_name,
    cs.gross_sales,
    COALESCE(SUM(ps.amount_paid), 0.00) AS total_payment_from_splits,
    cs.received_amount AS customer_sales_received_col
FROM customer_sales cs
LEFT JOIN payment_splits ps ON cs.sale_id = ps.sale_id
GROUP BY cs.sale_id, cs.name, cs.product_name, cs.gross_sales, cs.received_amount
ORDER BY cs.sale_id ASC;

-- Query 13: Show branch-wise total gross sales (using JOIN & GROUP BY).
-- Description: Summarizes total sales generated by each branch.
SELECT 
    b.branch_name,
    COALESCE(SUM(cs.gross_sales), 0.00) AS branch_total_gross_sales
FROM branches b
INNER JOIN customer_sales cs ON b.branch_id = cs.branch_id
GROUP BY b.branch_id, b.branch_name
ORDER BY branch_total_gross_sales DESC;

-- Query 14: Display sales along with payment method used.
-- Description: Displays every sale transaction paired with the payment method used.
SELECT 
    cs.sale_id,
    cs.name AS customer_name,
    cs.product_name,
    ps.payment_id,
    ps.amount_paid,
    ps.payment_method,
    ps.payment_date
FROM customer_sales cs
INNER JOIN payment_splits ps ON cs.sale_id = ps.sale_id
ORDER BY cs.sale_id ASC, ps.payment_id ASC;

-- Query 15: Retrieve sales along with branch admin name.
-- Description: Links sales transactions to the administrator managing that branch.
SELECT 
    cs.sale_id,
    b.branch_name,
    b.branch_admin_name,
    cs.name AS customer_name,
    cs.product_name,
    cs.gross_sales,
    cs.status
FROM customer_sales cs
INNER JOIN branches b ON cs.branch_id = b.branch_id
ORDER BY cs.sale_id ASC;


-- =======================================================================
-- SECTION 4: FINANCIAL TRACKING QUERIES
-- =======================================================================

-- Query 16: Find sales where the pending amount is greater than 5000.
-- Description: Pinpoints high outstanding accounts for collection follow-up.
SELECT 
    sale_id,
    branch_id,
    date,
    name AS customer_name,
    mobile_number,
    product_name,
    gross_sales,
    received_amount,
    pending_amount,
    status
FROM customer_sales
WHERE pending_amount > 5000.00
ORDER BY pending_amount DESC;

-- Query 17: Retrieve top 3 highest gross sales.
-- Description: Identifies the 3 largest transactions in the system.
SELECT 
    sale_id,
    branch_id,
    date,
    name AS customer_name,
    product_name,
    gross_sales,
    status
FROM customer_sales
ORDER BY gross_sales DESC
LIMIT 3;

-- Query 18: Find the branch with highest total gross sales.
-- Description: Determines the top-performing revenue-generating branch.
SELECT 
    b.branch_name,
    b.branch_admin_name,
    SUM(cs.gross_sales) AS total_gross_sales
FROM branches b
INNER JOIN customer_sales cs ON b.branch_id = cs.branch_id
GROUP BY b.branch_id, b.branch_name, b.branch_admin_name
ORDER BY total_gross_sales DESC
LIMIT 1;

-- Query 19: Retrieve monthly sales summary (group by month & year).
-- Description: Groups sales performance across timeline months.
SELECT 
    DATE_FORMAT(date, '%Y-%m') AS sales_month,
    COUNT(sale_id) AS total_transactions,
    SUM(gross_sales) AS total_gross_sales,
    SUM(received_amount) AS total_received_amount,
    SUM(pending_amount) AS total_pending_amount
FROM customer_sales
GROUP BY DATE_FORMAT(date, '%Y-%m')
ORDER BY sales_month ASC;

-- Query 20: Calculate payment method-wise total collection (Cash / UPI / Card).
-- Description: Analyzes collections across payment modalities.
SELECT 
    payment_method,
    COUNT(payment_id) AS transaction_count,
    SUM(amount_paid) AS total_collection,
    ROUND((SUM(amount_paid) / (SELECT SUM(amount_paid) FROM payment_splits)) * 100, 2) AS percentage_share
FROM payment_splits
GROUP BY payment_method
ORDER BY total_collection DESC;
